import db from '../../../config/db.js'; // Pastikan path koneksi MySQL kamu sudah benar

class WarungRepository {
  // 1. Ambil Semua Warung
  async findAllWarungs() {
    return new Promise((resolve, reject) => {
      db.query('SELECT * FROM warung', (err, results) => {
        if (err) return reject(err);
        resolve(results);
      });
    });
  }

  // 2. Tambah Warung Baru + Auto Generate ID Urut (WRG-001, WRG-002, dst)
  async createWarung(payload) {
    return new Promise((resolve, reject) => {
      const { nama_warung, pemilik, kota, kecamatan, tanggal_daftar, status } = payload;

      // Ambil ID warung dengan angka urutan tertinggi di database saat ini
      const checkQuery = `SELECT id_warung FROM warung ORDER BY id_warung DESC LIMIT 1`;

      db.query(checkQuery, [], (err, results) => {
        if (err) return reject(err);

        let nextWarungNumber = 1;

        // Jika sudah ada warung terdaftar, ambil ID terakhir lalu naikkan + 1
        if (results.length > 0) {
          const lastId = results[0].id_warung; 
          const lastNumber = parseInt(lastId.replace('WRG-', ''), 10); // Mengambil angka "002" -> 2
          nextWarungNumber = lastNumber + 1;
        }

        // Format nomor urut agar selalu ber-padding 3 digit (misal: 3 -> "003")
        const formattedNumber = String(nextWarungNumber).padStart(3, '0');
        const autoGeneratedId = `WRG-${formattedNumber}`;

        // Menggunakan waktu hari ini jika tanggal_daftar tidak dikirim dari FE
        const finalTanggalDaftar = tanggal_daftar || new Date().toISOString().split('T')[0];

        const insertQuery = `
          INSERT INTO warung (id_warung, nama_warung, pemilik, kota, kecamatan, tanggal_daftar, status)
          VALUES (?, ?, ?, ?, ?, ?, ?)
        `;

        db.query(
          insertQuery, 
          [autoGeneratedId, nama_warung, pemilik, kota, kecamatan, finalTanggalDaftar, status || 'Aktif'], 
          (insertErr, result) => {
            if (insertErr) return reject(insertErr);
            
            resolve({ id_warung: autoGeneratedId, affectedRows: result.affectedRows });
          }
        );
      });
    });
  }

  // 3. Ambil Satu Warung Berdasarkan ID (WRG-XXX)
  async getWarungById(id) {
    return new Promise((resolve, reject) => {
      db.query('SELECT * FROM warung WHERE id_warung = ?', [id], (err, results) => {
        if (err) return reject(err);
        resolve(results[0]); // Mengembalikan objek tunggal warung
      });
    });
  }

  // 4. Update Data Warung Berdasarkan ID
  async updateWarungById(id, payload) {
    return new Promise((resolve, reject) => {
      const { nama_warung, pemilik, kota, kecamatan, status } = payload;
      
      const query = `
        UPDATE warung 
        SET nama_warung = ?, pemilik = ?, kota = ?, kecamatan = ?, status = ?
        WHERE id_warung = ?
      `;

      db.query(
        query, 
        [nama_warung, pemilik, kota, kecamatan, status, id], 
        (err, result) => {
          if (err) return reject(err);
          resolve(result);
        }
      );
    });
  }

  // 5. Hapus Warung Berdasarkan ID
  async deleteWarungById(id) {
    return new Promise((resolve, reject) => {
      db.query('DELETE FROM warung WHERE id_warung = ?', [id], (err, result) => {
        if (err) return reject(err);
        resolve(result);
      });
    });
  }
}

export default new WarungRepository();