// src/services/product/repositories/product-repositories.js
import db from '../../../config/db.js';

class ProductRepository {
  // 1. AMBIL SEMUA PRODUK
  async findAllProducts(id_warung) {
    return new Promise((resolve, reject) => {
      const query = 'SELECT * FROM produk WHERE id_warung = ?';
      
      db.query(query, [id_warung], (err, results) => {
        if (err) {
          console.error('❌ Error MySQL saat findAllProducts:', err.message);
          return reject(err);
        }
        resolve(results);
      });
    });
  }

  // 2. TAMBAH PRODUK BARU + AUTO GENERATE ID (PRD-NNN-NNN) Berbasis ID Warung Asli
  async createProduct(payload) {
    return new Promise((resolve, reject) => {
      const { id_warung, nama_produk, harga_jual, harga_pokok, kategori_produk, status } = payload;
      
      // Ambil angka tengah/kode dari ID warung (Contoh: 'WRG-002' -> diambil '002')
      const kodeWarung = id_warung.split('-')[1] || '001';

      // Cari nomor urut terakhir produk milik warung YANG SEDANG LOGIN ini
      const checkQuery = `SELECT id_produk FROM produk WHERE id_warung = ? ORDER BY id_produk DESC LIMIT 1`;

      db.query(checkQuery, [id_warung], (err, results) => {
        if (err) return reject(err);

        let nextProductNumber = 1;

        // Jika warung ini sudah memiliki produk, naikkan nomor urut terakhirnya + 1
        if (results.length > 0) {
          const lastId = results[0].id_produk;
          const lastNumber = parseInt(lastId.split('-')[2]); // Ambil angka paling belakang "005" -> 5
          nextProductNumber = lastNumber + 1;
        }

        // Format nomor urut agar selalu 3 digit (misal: 1 -> "001")
        const formattedProductNumber = String(nextProductNumber).padStart(3, '0');
        
        // Hasilnya dinamis! Jika warung WRG-002, id menjadi: PRD-002-001
        const autoGeneratedId = `PRD-${kodeWarung}-${formattedProductNumber}`;

        const insertQuery = `
          INSERT INTO produk (id_produk, id_warung, nama_produk, harga_jual, harga_pokok, kategori_produk, status)
          VALUES (?, ?, ?, ?, ?, ?, ?)
        `;

        db.query(
          insertQuery, 
          [autoGeneratedId, id_warung, nama_produk, harga_jual, harga_pokok, kategori_produk, status || 'Aktif'], 
          (insertErr, result) => {
            if (insertErr) return reject(insertErr);
            resolve({ id_produk: autoGeneratedId, affectedRows: result.affectedRows });
          }
        );
      });
    });
  }

  // 3. AMBIL SATU PRODUK BERDASARKAN ID (Sudah Sempurna!)
  async getProductById(id) {
    return new Promise((resolve, reject) => {
      db.query('SELECT id_produk, id_warung, nama_produk, harga_jual, harga_pokok, kategori_produk, status FROM produk WHERE id_produk = ?', [id], (err, results) => {
        if (err) return reject(err);
        resolve(results[0]);
      });
    });
  }

  // 4. UPDATE DATA PRODUK BERDASARKAN ID (Sudah Sempurna!)
  async updateProductById(id, payload) {
    return new Promise((resolve, reject) => {
      const { nama_produk, harga_jual, harga_pokok, kategori_produk, status } = payload;
      
      const query = `
        UPDATE produk 
        SET nama_produk = ?, harga_jual = ?, harga_pokok = ?, kategori_produk = ?, status = ?
        WHERE id_produk = ?
      `;

      db.query(
        query, 
        [nama_produk, harga_jual, harga_pokok, kategori_produk, status, id], 
        (err, result) => {
          if (err) return reject(err);
          resolve(result);
        }
      );
    });
  }

  // 5. HAPUS PRODUK BERDASARKAN ID (Sudah Sempurna!)
  async deleteProductById(id) {
    return new Promise((resolve, reject) => {
      db.query('DELETE FROM produk WHERE id_produk = ?', [id], (err, result) => {
        if (err) return reject(err);
        resolve(result);
      });
    });
  }
}

export default new ProductRepository();